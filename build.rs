use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    studio();
    // The `dylib` feature (dev builds) links the dependencies, and with them Rust's std, dynamically. Cargo puts
    // std's directory on the library path for `cargo run` and `cargo test`; this rpath lets the binaries run outside
    // cargo too.
    if std::env::var_os("CARGO_FEATURE_DYLIB").is_none() {
        return;
    }
    let rustc = std::env::var("RUSTC").unwrap_or_else(|_| "rustc".into());
    let out = std::process::Command::new(rustc)
        .args(["--print", "target-libdir"])
        .output()
        .expect("rustc --print target-libdir");
    let dir = String::from_utf8(out.stdout).expect("target-libdir is UTF-8");
    println!("cargo:rustc-link-arg=-Wl,-rpath,{}", dir.trim());
}

/// The Studio (`studio/`, a web app built with Node into `studio/dist`), embedded in the binary: OUT_DIR/studio.rs
/// lists every file of `studio/dist` by its path there, each `include_bytes!`'d, for `src/server/studio.rs`. Cargo
/// never needs Node: without a build the list is empty and `/studio/` says how to make one.
///
/// What Cargo watches to run this again: `studio/dist` once it exists (a new build replaces its files), else `studio`
/// (where the build appears). Never a path that doesn't exist, which Cargo would take as changed on every build.
fn studio() {
    let root = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let dist = root.join("studio").join("dist");
    let mut files = Vec::new();
    if dist.join("index.html").is_file() {
        println!("cargo:rerun-if-changed=studio/dist");
        walk(&dist, &dist, &mut files);
        files.sort();
    } else if dist.exists() {
        // A build under way, or one that failed: watched, and served as no build.
        println!("cargo:rerun-if-changed=studio/dist");
    } else if root.join("studio").is_dir() {
        println!("cargo:rerun-if-changed=studio");
    }
    let mut code = String::from(
        "// Generated by build.rs from studio/dist.\npub(super) static FILES: &[(&str, &[u8])] = &[\n",
    );
    for (name, path) in &files {
        code.push_str(&format!("    ({name:?}, include_bytes!({path:?})),\n"));
    }
    code.push_str("];\n");
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR")).join("studio.rs");
    // Unchanged contents aren't written again, so nothing that includes them rebuilds for it.
    if std::fs::read_to_string(&out).ok().as_deref() != Some(code.as_str()) {
        std::fs::write(&out, code).expect("write OUT_DIR/studio.rs");
    }
}

/// Every file under `dir`, as (its path under `base` with `/` separators, its absolute path). Dotfiles are left out.
fn walk(base: &Path, dir: &Path, files: &mut Vec<(String, String)>) {
    let entries = std::fs::read_dir(dir).unwrap_or_else(|e| panic!("read {}: {e}", dir.display()));
    for e in entries {
        let e = e.expect("a studio/dist entry");
        let path = e.path();
        if e.file_name().to_string_lossy().starts_with('.') {
            continue;
        }
        if path.is_dir() {
            walk(base, &path, files);
        } else {
            let name = path.strip_prefix(base).expect("under studio/dist");
            let name = name
                .components()
                .map(|c| c.as_os_str().to_string_lossy())
                .collect::<Vec<_>>()
                .join("/");
            files.push((name, path.display().to_string()));
        }
    }
}
